export function getLangMeta(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

export function createTranslator(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.id;
  const fallback = lang === 'id' ? TRANSLATIONS.en : TRANSLATIONS.en;
  return (key) => dict[key] ?? fallback[key] ?? TRANSLATIONS.id[key] ?? key;
}

export function translateStatus(status, t) {
  if (status === 'Low') return t('statusLow');
  if (status === 'High') return t('statusHigh');
  return t('statusNormal');
}
